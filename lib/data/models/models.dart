class CyclosUser {
  CyclosUser({required this.id, required this.display, this.shortDisplay, this.subtitle});
  final String id;
  final String display;
  final String? shortDisplay;

  /// Secondary line in search results: username, phone or account number.
  final String? subtitle;

  String get initials {
    final parts = display.trim().split(RegExp(r'\s+')).where((p) => p.isNotEmpty);
    return parts.take(2).map((p) => p[0].toUpperCase()).join();
  }

  factory CyclosUser.fromJson(Map<String, dynamic> j) {
    final extra = [j['username'], j['accountNumber'], j['phone']]
        .where((v) => v != null && v.toString().isNotEmpty)
        .map((v) => v.toString())
        .toList();
    return CyclosUser(
      id: j['id'].toString(),
      display: (j['display'] ?? j['name'] ?? '').toString(),
      shortDisplay: j['shortDisplay']?.toString(),
      subtitle: extra.isEmpty ? null : extra.join(' · '),
    );
  }
}

class Account {
  Account({
    required this.id,
    required this.typeId,
    required this.typeKey,
    required this.typeName,
    required this.number,
    required this.balance,
    required this.available,
  });

  final String id;

  /// Account type internal name (or id) used in history URLs.
  final String typeId;

  /// Account type id, as used by payment types' `from.id`.
  final String typeKey;
  final String typeName;
  final String? number;
  final num balance;
  final num available;

  String get maskedNumber {
    final n = number;
    if (n == null || n.length < 4) return '';
    return '•••• ${n.substring(n.length - 4)}';
  }

  /// Cyclos AccountWithStatus: {id, number, type:{id, internalName, name},
  /// status:{balance, availableBalance, ...}}
  factory Account.fromJson(Map<String, dynamic> j) {
    final type = (j['type'] as Map?)?.cast<String, dynamic>() ?? const {};
    final status = (j['status'] as Map?)?.cast<String, dynamic>() ?? const {};
    return Account(
      id: j['id'].toString(),
      typeId: (type['internalName'] ?? type['id']).toString(),
      typeKey: type['id'].toString(),
      typeName: (type['name'] ?? '').toString(),
      number: j['number']?.toString(),
      balance: Money.parse(status['balance']),
      available: Money.parse(status['availableBalance'] ?? status['balance']),
    );
  }
}

class HistoryEntry {
  HistoryEntry({
    required this.id,
    required this.date,
    required this.amount,
    required this.title,
    this.description,
    this.transactionNumber,
  });

  final String id;
  final DateTime date;
  final num amount;
  final String title;
  final String? description;
  final String? transactionNumber;

  bool get isCredit => amount > 0;

  /// Key for GET /transfers/{key}: the transaction number (escaped when all
  /// digits) or the id — as the official banking helper does.
  String get key {
    final n = transactionNumber;
    if (n == null || n.trim().isEmpty) return id;
    return RegExp(r'^[-+]?\d+$').hasMatch(n.trim()) ? "'${n.trim()}" : n.trim();
  }

  factory HistoryEntry.fromJson(Map<String, dynamic> j) {
    final related = (j['relatedAccount'] as Map?)?.cast<String, dynamic>();
    final relatedUser = (related?['user'] as Map?)?.cast<String, dynamic>();
    final type = (j['type'] as Map?)?.cast<String, dynamic>();
    final title = relatedUser?['display'] ??
        (related?['type'] as Map?)?['name'] ??
        type?['name'] ??
        'Transaction';
    return HistoryEntry(
      id: j['id'].toString(),
      date: DateTime.tryParse(j['date']?.toString() ?? '')?.toLocal() ??
          DateTime.now(),
      amount: Money.parse(j['amount']),
      title: title.toString(),
      description: j['description']?.toString(),
      transactionNumber: j['transactionNumber']?.toString(),
    );
  }
}

/// GET /transfers/{key} (Cyclos TransferView), shown as a receipt.
class TransferDetails {
  TransferDetails({
    required this.id,
    required this.date,
    required this.amount,
    required this.fromName,
    required this.toName,
    this.fromAccount,
    this.toAccount,
    this.typeName,
    this.description,
    this.transactionNumber,
    this.fees = const [],
    this.statuses = const [],
    this.channel,
  });

  final String id;
  final DateTime date;
  final num amount;
  final String fromName;
  final String toName;
  final String? fromAccount;
  final String? toAccount;
  final String? typeName;
  final String? description;
  final String? transactionNumber;

  /// Fees generated by this transfer (its `children`): (name, amount).
  final List<(String, num)> fees;
  final List<String> statuses;
  final String? channel;

  static String _party(Map? acc) {
    if (acc == null) return '';
    final user = acc['user'] as Map?;
    if (user != null) return (user['display'] ?? '').toString();
    final type = acc['type'] as Map?;
    return (type?['name'] ?? 'Nchemty').toString();
  }

  factory TransferDetails.fromJson(Map<String, dynamic> j) {
    final from = j['from'] as Map?;
    final to = j['to'] as Map?;
    final children = (j['children'] as List?) ?? const [];
    final statuses = j['statuses'];
    final tx = j['transaction'] as Map?;
    return TransferDetails(
      id: j['id'].toString(),
      date: DateTime.tryParse(j['date']?.toString() ?? '')?.toLocal() ?? DateTime.now(),
      amount: Money.parse(j['amount']),
      fromName: _party(from),
      toName: _party(to),
      fromAccount: ((from?['type'] as Map?)?['name'])?.toString(),
      toAccount: ((to?['type'] as Map?)?['name'])?.toString(),
      typeName: ((j['type'] as Map?)?['name'])?.toString(),
      description: j['description']?.toString(),
      transactionNumber: j['transactionNumber']?.toString(),
      fees: [
        for (final c in children)
          if (c is Map)
            (
              ((c['type'] as Map?)?['name'] ?? 'Fee').toString(),
              Money.parse(c['amount']),
            ),
      ],
      statuses: [
        if (statuses is Map)
          for (final v in statuses.values)
            if (v is Map && v['name'] != null) v['name'].toString(),
      ],
      channel: ((tx?['channel'] as Map?)?['name'])?.toString(),
    );
  }
}

